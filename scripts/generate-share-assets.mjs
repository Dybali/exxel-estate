// Regenerates lib/share-image-assets.ts (font and logo for the listing share card,
// app/ilan/[id]/share-image) and public/og-default.png (default share image for all other pages).
//
//   node scripts/generate-share-assets.mjs
//
// Font: next/og (satori) reads TTF/OTF/WOFF only, not the WOFF2 Inter files in public/fonts. Until a
// static Inter TTF with latin-ext is added (place it at public/fonts/Inter-SemiBold.ttf and run this
// script again), Geist Regular (SIL OFL, shipped with Next.js) is embedded; it covers Turkish (ı ş ğ İ),
// Western European and Cyrillic letters. The data is embedded as base64 so the same module works in the
// Cloudflare Worker (no file system) and the Node standalone server.
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const require = createRequire(import.meta.url);
const interPath = path.join(root, "public/fonts/Inter-SemiBold.ttf");
const fontPath = fs.existsSync(interPath) ? interPath : path.join(path.dirname(require.resolve("next/package.json")), "dist/compiled/@vercel/og/Geist-Regular.ttf");
const fontName = fontPath === interPath ? "Inter" : "Geist";
const font = fs.readFileSync(fontPath);
const logo = fs.readFileSync(path.join(root, "public/brand/logo-horizontal-negativ.svg"), "utf8").trim();

const module = `// Generated by scripts/generate-share-assets.mjs. Do not edit by hand.
// ${fontName} font (SIL Open Font License) and the negative horizontal logo for share images.
export const SHARE_FONT_NAME = ${JSON.stringify(fontName)};
export const SHARE_FONT_BASE64 = ${JSON.stringify(font.toString("base64"))};
export const SHARE_LOGO_SVG = ${JSON.stringify(logo)};
`;
fs.writeFileSync(path.join(root, "lib/share-image-assets.ts"), module);
console.log(`lib/share-image-assets.ts: ${fontName} (${font.length} bytes), logo ${logo.length} bytes`);

// Default share image: rendered with the same renderer next/og uses on Node.
const { ImageResponse } = await import(path.join(path.dirname(require.resolve("next/package.json")), "dist/compiled/@vercel/og/index.node.js").replace(/\\/g, "/").replace(/^([A-Za-z]):/, "file:///$1:"));
const React = (await import("react")).default;
const h = React.createElement;
const logoUri = `data:image/svg+xml;base64,${Buffer.from(logo).toString("base64")}`;
const petrol = "#0b5f63", gold = "#f2b84b";
const element = h("div", { style: { width: "100%", height: "100%", display: "flex", flexDirection: "column", justifyContent: "space-between", background: `linear-gradient(135deg, ${petrol} 0%, #084a4d 100%)`, color: "#fff", fontFamily: fontName, padding: "72px 80px" } },
  h("img", { src: logoUri, width: 506, height: 94 }),
  h("div", { style: { display: "flex", flexDirection: "column" } },
    h("div", { style: { width: 96, height: 8, background: gold, borderRadius: 4, marginBottom: 32 } }),
    h("div", { style: { fontSize: 64, lineHeight: 1.12 } }, "Türkiye'de satılık ve kiralık gayrimenkuller"),
    h("div", { style: { fontSize: 32, marginTop: 24, color: "rgba(255,255,255,.78)" } }, "İlanlar · Projeler · Şirketler · 8 dil")),
);
const response = new ImageResponse(element, { width: 1200, height: 630, fonts: [{ name: fontName, data: font, weight: 400, style: "normal" }] });
const png = Buffer.from(await response.arrayBuffer());
fs.writeFileSync(path.join(root, "public/og-default.png"), png);
console.log(`public/og-default.png: ${png.length} bytes`);
